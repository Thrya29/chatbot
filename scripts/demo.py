"""Run the six case-study conversations end to end and write the results.

    python scripts/demo.py

Outputs:
  reports/demo_transcripts.md   what the client saw, turn by turn
  reports/agent_view.html       what each human agent saw on arrival
"""
from __future__ import annotations

import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from handoff_lab.agent_view import page          # noqa: E402
from handoff_lab.lab import Lab                  # noqa: E402
from handoff_lab.mock_genesys import Agent       # noqa: E402

SCENARIOS = [
    dict(name="1. Withdraw to a different bank account", client="client-1",
         turns=["How do I withdraw funds to a different bank account?"]),
    dict(name="2. Third message about a withdrawal that hasn't arrived", client="client-2",
         history=["Where is my withdrawal?", "My withdrawal still hasn't arrived"],
         turns=["You keep telling me the same thing. This is useless. Get me a person."],
         details=["amount £2,500", "requested 22 Oct", "account ending 4417", "checked with their bank on 27 Oct"],
         told=["26 Oct: 'Withdrawal times' article", "27 Oct: 'Withdrawal times' article"]),
    dict(name="3. Close-out dispute with regulator and solicitor threat", client="client-3",
         turns=["You closed my position at the worst possible price. This is theft. I'm going to the regulator "
                "and my solicitor."]),
    dict(name="4. Possible vulnerability", client="client-4",
         turns=["I've lost nearly everything this month. I can't stop trading. I don't know what I'm going to "
                "tell my family."]),
    dict(name="5. Lost authenticator, open positions, market opens in 20 minutes", client="client-5",
         turns=["I lost my phone and can't get into my authenticator. I have open positions and the market "
                "opens in 20 minutes."]),
    dict(name="6. Saturday 02:00, unrecognised withdrawal", client="client-6",
         now=datetime(2026, 10, 31, 2, 0), night=True,
         turns=["There's a withdrawal request on my account I didn't make. I want to speak to a person."]),
    dict(name="Extra: withdrawal still inside its window", client="client-7",
         turns=["Where is my withdrawal? It hasn't arrived yet."]),
]


def main() -> None:
    out = ROOT / "reports"
    out.mkdir(exist_ok=True)
    md, convs = ["# Demo: six case conversations, end to end\n",
                 "Synthetic clients and data. Generated by `python scripts/demo.py`.\n"], []
    for sc in SCENARIOS:
        lab = Lab(now=sc.get("now", datetime(2026, 10, 28, 10, 40)))
        if sc.get("night"):      # reduced overnight team: nobody on Security until the morning shift
            lab.staff(Agent("Ana", {"PriorityVulnerable"}, {"en"}))
        else:
            lab.staff(Agent("Priya", {"FundingPayments", "Complaints"}, {"en"}),
                      Agent("Wei", {"FundingPayments", "AccountKYC", "Security"}, {"en", "zh"}),
                      Agent("Sam", {"PriorityVulnerable", "Complaints", "Security"}, {"en"}))
        t = lab.platform.open_thread(sc["client"])
        for m in sc.get("history", []):
            lab.platform.client_says(t.id, m, "hist")
        for turn in sc["turns"]:
            res = lab.client_turn(t.id, turn, sc.get("history"), details_given=sc.get("details"),
                                  ai_told_them=sc.get("told"))
        md.append(f"\n## {sc['name']}\n")
        md.append(f"**Tier:** {res.decision.tier} · **Action:** {res.decision.action} · "
                  f"**Queue:** {res.decision.queue or '-'} · **Priority:** {res.decision.priority or '-'} · "
                  f"**Flags:** {', '.join(sorted(res.decision.flags)) or 'none'}\n")
        for who, text in lab.platform.threads[t.id].messages:
            md.append(f"- **{who}:** {text}")
        if lab.genesys.conversations:
            conv = next(iter(lab.genesys.conversations.values()))
            convs.append(conv)
            md.append(f"\n*Genesys:* {conv.id}, queue {conv.queue}, {conv.priority}, routed by "
                      f"{conv.routed_by}, agent {conv.agent or 'waiting (out of hours)'}")
    (out / "demo_transcripts.md").write_text("\n".join(md) + "\n")
    (out / "agent_view.html").write_text(page(convs, "What the agent sees on arrival (synthetic demo)"))
    print("wrote reports/demo_transcripts.md and reports/agent_view.html")


if __name__ == "__main__":
    main()
